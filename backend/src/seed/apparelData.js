const generateVariants = (prodName, skuPrefix, colors, price, mrp, stockPerColor = 50) => {
  const sizes = ['S', 'M', 'L', 'XL', '2XL'];
  return colors.map((col, idx) => {
    const cleanCol = col.name.replace(/[^a-zA-Z0-9]/g, '').toUpperCase().slice(0, 4);
    return {
      variant_name: `${prodName} - ${col.name}`,
      color: col.name,
      color_code: col.hex,
      sku: `${skuPrefix}-${cleanCol}`,
      price,
      b2b_price: price,
      b2c_price: mrp,
      mrp,
      stock: stockPerColor,
      sizes,
      image: col.image || '',
      attributes: {
        color: col.name,
        hex: col.hex,
        available_sizes: sizes,
      },
    };
  });
};

